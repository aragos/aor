/** Interpolation is presentation-only. Unknown placeholders remain visible to completeness checks. */
export function t(key: string, values: Record<string, string | number> = {}): string {
    return (en[key] ?? key).replace(/\{(\w+)\}/g, (placeholder, name: string) =>
        values[name] === undefined ? placeholder : typeof values[name] === 'number'
            ? new Intl.NumberFormat('en-US').format(values[name]) : values[name]);
}

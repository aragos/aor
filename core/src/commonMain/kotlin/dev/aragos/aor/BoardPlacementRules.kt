package dev.aragos.aor

import kotlinx.collections.immutable.toPersistentMap

/**
 * A validated action. Its board snapshot prevents resolving it after an unrelated board mutation.
 */
sealed interface PlacementPlan {
    val player: PlayerId
    val destination: ProvinceId
    val addedTokens: Int
    val route: ExpansionRoute
    val boardBefore: BoardState

    @ConsistentCopyVisibility
    data class Peaceful
    internal constructor(
        override val player: PlayerId,
        override val destination: ProvinceId,
        override val addedTokens: Int,
        override val route: ExpansionRoute,
        override val boardBefore: BoardState,
    ) : PlacementPlan

    /**
     * The driver reserves [addedTokens] and shipping usage before requesting a recorded outcome.
     */
    @ConsistentCopyVisibility
    data class Competition
    internal constructor(
        override val player: PlayerId,
        override val destination: ProvinceId,
        override val addedTokens: Int,
        override val route: ExpansionRoute,
        override val boardBefore: BoardState,
        val existingTokens: Int,
        val defenders: Set<PlayerId>,
        val breakdown: AttackBreakdown,
    ) : PlacementPlan
}

/** A legal placement or its typed blocker. Projections do not construct command exceptions. */
internal class PlacementAssessment
private constructor(
    val plan: PlacementPlan?,
    val blocker: ViolationCode?,
    private val intermediate: ProvinceId?,
) {
    constructor(plan: PlacementPlan) : this(plan, null, null)

    constructor(
        blocker: ViolationCode,
        intermediate: ProvinceId? = null,
    ) : this(null, blocker, intermediate)

    fun requirePlan(destination: ProvinceId): PlacementPlan {
        plan?.let {
            return it
        }
        val code = checkNotNull(blocker) { "A blocked placement must retain its diagnostic." }
        val affected =
            if (code == ViolationCode.SHIPPING_CAPACITY_EXCEEDED) listOf(destination.value)
            else listOfNotNull(intermediate?.value)
        throw RuleViolation(code, entityIds = affected)
    }
}

object BoardPlacementRules {
    /**
     * Chooses the first feasible route in [ExpansionReach.routesTo] preference order for the
     * requested commitment. Queries and execution use the same plan, including capacity checks.
     */
    fun evaluate(
        context: BoardRulesContext,
        player: PlayerId,
        destination: ProvinceId,
        addedTokens: Int,
        poolTokens: Int,
    ): PlacementPlan {
        context.province(destination)
        return assessGeneratedRoutes(
                context,
                player,
                destination,
                addedTokens,
                poolTokens,
                ExpansionReach.routesTo(context, player, destination),
            )
            .requirePlan(destination)
    }

    /** All rejection checks run before the driver spends tokens, shipping capacity or any dice. */
    fun evaluate(
        context: BoardRulesContext,
        player: PlayerId,
        destination: ProvinceId,
        addedTokens: Int,
        route: ExpansionRoute,
        poolTokens: Int,
    ): PlacementPlan {
        poolBlocker(addedTokens, poolTokens)?.let { throw RuleViolation(it) }
        ExpansionReach.validate(context, player, destination, route)
        return assessOnRoute(context, player, destination, addedTokens, route)
            .requirePlan(destination)
    }

    /**
     * Admit routes generated by [ExpansionReach.routesTo] for this exact context and actor. The
     * generated routes already establish reach. Pool, shipping and placement still vary with the
     * requested commitment.
     */
    internal fun assessGeneratedRoutes(
        context: BoardRulesContext,
        player: PlayerId,
        destination: ProvinceId,
        addedTokens: Int,
        poolTokens: Int,
        routes: List<ExpansionRoute>,
    ): PlacementAssessment {
        if (routes.isEmpty()) {
            val intermediate =
                ExpansionReach.blockedCaravanIntermediate(context, player, destination)
            return if (intermediate == null) PlacementAssessment(ViolationCode.UNREACHABLE_PROVINCE)
            else PlacementAssessment(ViolationCode.CARAVAN_INTERMEDIATE_OCCUPIED, intermediate)
        }
        poolBlocker(addedTokens, poolTokens)?.let {
            return PlacementAssessment(it)
        }
        var firstBlocked: PlacementAssessment? = null
        for (route in routes) {
            val assessment = assessOnRoute(context, player, destination, addedTokens, route)
            if (assessment.plan != null) return assessment
            if (firstBlocked == null) firstBlocked = assessment
        }
        return checkNotNull(firstBlocked) { "A nonempty route assessment must have a result." }
    }

    private fun poolBlocker(addedTokens: Int, poolTokens: Int): ViolationCode? =
        when {
            addedTokens < 0 -> ViolationCode.INVALID_PLACEMENT
            poolTokens < 0 || addedTokens > poolTokens ->
                ViolationCode.INSUFFICIENT_EXPANSION_TOKENS
            else -> null
        }

    private fun assessOnRoute(
        context: BoardRulesContext,
        player: PlayerId,
        destination: ProvinceId,
        addedTokens: Int,
        route: ExpansionRoute,
    ): PlacementAssessment {
        if (route is ExpansionRoute.Shipping) {
            ExpansionReach.shippingCapacityBlocker(context, player, destination, addedTokens)?.let {
                return PlacementAssessment(it)
            }
        }
        val definition = context.province(destination)
        val occupants = context.board.pieces[destination]
        val holdings = (occupants as? ProvincePieces.Tokens)?.holdings.orEmpty()
        val remaining = peacefulCapacity(occupants, definition.marketNumber)
        val existing = holdings[player]?.total ?: 0
        val defenders =
            when (occupants) {
                is ProvincePieces.Marker -> setOf(occupants.owner) - player
                else -> holdings.keys - player
            }
        if (occupants is ProvincePieces.Marker && occupants.owner == player) {
            return PlacementAssessment(ViolationCode.INVALID_PLACEMENT)
        }
        val competition =
            defenders.isNotEmpty() &&
                (occupants is ProvincePieces.Marker || addedTokens > remaining)
        if (competition) {
            val breakdown = CompetitionRules.requirement(context, player, destination)
            if (!breakdown.requirement.accepts(existing, addedTokens)) {
                return PlacementAssessment(ViolationCode.INVALID_ATTACK_TOKEN_COUNT)
            }
            if (!markerAvailable(context, player, definition)) {
                return PlacementAssessment(ViolationCode.NO_DOMINATION_MARKERS)
            }
            return PlacementAssessment(
                PlacementPlan.Competition(
                    player,
                    destination,
                    addedTokens,
                    route,
                    context.board,
                    existing,
                    defenders,
                    breakdown,
                )
            )
        }
        if (addedTokens !in 1..remaining) {
            return PlacementAssessment(ViolationCode.INVALID_PLACEMENT)
        }
        if (
            defenders.isEmpty() &&
                existing + addedTokens == definition.marketNumber &&
                !markerAvailable(context, player, definition)
        ) {
            return PlacementAssessment(ViolationCode.NO_DOMINATION_MARKERS)
        }
        return PlacementAssessment(
            PlacementPlan.Peaceful(player, destination, addedTokens, route, context.board)
        )
    }

    /** Number of additional tokens the province's pieces can accept without competition. */
    internal fun peacefulCapacity(occupants: ProvincePieces?, marketNumber: Int): Int =
        when (occupants) {
            is ProvincePieces.Marker -> 0
            is ProvincePieces.Tokens -> marketNumber - occupants.total
            null -> marketNumber
        }

    /** Peaceful placement spends [BoardChange.tokensRequired] from the expansion pool. */
    fun applyPeaceful(context: BoardRulesContext, plan: PlacementPlan.Peaceful): BoardChange {
        checkRule(context.board == plan.boardBefore, ViolationCode.INVALID_BOARD_MUTATION)
        val definition = context.province(plan.destination)
        val previous =
            (context.board.pieces[plan.destination] as? ProvincePieces.Tokens)?.holdings.orEmpty()
        val holding =
            previous[plan.player]?.add(plan.addedTokens, PieceSide.WHITE)
                ?: TokenHolding(white = plan.addedTokens)
        val holdings = (previous + (plan.player to holding)).toPersistentMap()
        if (
            holdings.size == 1 &&
                holding.total == definition.marketNumber &&
                !definition.isSatellite
        ) {
            val replacement =
                context.board.placeMarker(plan.destination, plan.player, PieceSide.WHITE)
            return replacement.copy(
                tokensReturned = mapOf(plan.player to holding.total),
                tokensRequired = mapOf(plan.player to plan.addedTokens),
            )
        }
        return BoardChange(
            board =
                context.board.copy(
                    pieces =
                        context.board.pieces.putting(
                            plan.destination,
                            ProvincePieces.Tokens(holdings),
                        )
                ),
            tokensRequired = mapOf(plan.player to plan.addedTokens),
        )
    }

    /** Derive usage from the accepted plan; competition attempts remain charged after failure. */
    fun recordShipping(context: BoardRulesContext, plan: PlacementPlan): BoardRulesContext =
        if (plan.route is ExpansionRoute.Shipping) {
            context.recordShipment(plan.player, plan.destination, plan.addedTokens)
        } else {
            context
        }

    private fun markerAvailable(
        context: BoardRulesContext,
        player: PlayerId,
        definition: ProvinceDefinition,
    ): Boolean = definition.isSatellite || context.board.markerCount(player) < 25
}
